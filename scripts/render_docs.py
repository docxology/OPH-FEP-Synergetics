"""Render the registry, bound values, concordance and ontology supplement.

The registry and ``MANUSCRIPT_VALUES`` are the sources of truth, so the
reference documents are generated rather than hand-copied: a change to a claim,
a status or a probe value shows up in the next render and can be reviewed as an
ordinary diff.

Usage::

    python scripts/render_docs.py            # write the documents
    python scripts/render_docs.py --check    # fail if they are out of date
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Sequence

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "src"))

from scripts.manuscript_refs import index_references, read_sections  # noqa: E402
from oph_fep_synergetics.analysis import CORRESPONDENCES, summary, verify  # noqa: E402
from oph_fep_synergetics.analysis.provenance import load_sources  # noqa: E402
from oph_fep_synergetics.manuscript_variables import MANUSCRIPT_VALUES, token_for  # noqa: E402

DOCS = ROOT / "docs"

REGISTRY_DOC = DOCS / "CORRESPONDENCES.md"
VALUES_DOC = DOCS / "MANUSCRIPT_VALUES.md"
CONCORDANCE_DOC = DOCS / "CONCORDANCE.md"
ONTOLOGY_SOURCE = ROOT / "data" / "ontology_concordance.json"
ONTOLOGY_FILENAME = "90_ontology_concordance.md"
ONTOLOGY_DOC = ROOT / "manuscript" / ONTOLOGY_FILENAME

#: The manuscript's value tokens, as they appear in prose and figure captions.
TOKEN_CAPTION = re.compile(r"\{\{([A-Z][A-Z0-9_]*)\}\}")


def format_probe_value(value: object) -> str:
    """Render a probe value or bound value compactly and unambiguously."""
    if isinstance(value, dict):
        return ", ".join(f"{key}={format_probe_value(item)}" for key, item in value.items())
    if isinstance(value, (tuple, list)):
        return "(" + ", ".join(format_probe_value(item) for item in value) + ")"
    if isinstance(value, float):
        return f"{value!r}"
    return str(value)


def format_registry_measurement(name: str, value: object) -> str:
    """Keep printed precision portable while leaving raw probe values intact."""
    if isinstance(value, float):
        diagnostic = ("residual" in name or name.endswith("_error") or name in {
            "stationary_gradient_norm", "edge_spread", "f_zero_norm",
        })
        if diagnostic and abs(value) < 1e-9:
            return "abs < 1e-9"
        if value == 0:
            return "0"
        return format(value, ".9g")
    if isinstance(value, dict):
        return ", ".join(f"{key}={format_registry_measurement(str(key), item)}"
                         for key, item in value.items())
    if isinstance(value, (tuple, list)):
        return "(" + ", ".join(format_registry_measurement(name, item) for item in value) + ")"
    return format_probe_value(value)


def render_registry() -> str:
    results = {result.key: result for result in verify()}
    report = summary(tuple(results.values()))
    lines = [
        "# Correspondence registry",
        "",
        "<!-- generated by scripts/render_docs.py; edit the registry, then re-render -->",
        "",
        "One executable probe per entry. Each entry carries the operator-algebraic",
        "reading from Observer Patch Holography, the variational reading from the",
        "Free Energy Principle, and the geometric reading from Fuller's Synergetics,",
        "together with the status the probe establishes and the pair of programmes the",
        "claim is made across. Most claims are pairwise; `three-way` marks the few that",
        "no pair of readings captures.",
        "",
        "Measured floats are shown to nine significant digits; numerical error",
        "diagnostics below `1e-9` in magnitude are reported as such.",
        "`verify --json` retains raw values; probe tolerances are unchanged.",
        "",
        "| pair | kind | status | entry | claim |",
        "| --- | --- | --- | --- | --- |",
    ]
    for entry in CORRESPONDENCES:
        lines.append(
            f"| {entry.pair} | {entry.kind} | {entry.status} | `{entry.key}` | {entry.claim} |"
        )
    lines += [
        "",
        f"Totals: {report['passed']}/{report['total']} probes pass, "
        f"{report['failed']} fail.",
        "",
        "By kind:",
        "",
    ]
    for kind in ("isomorphism", "disagreement", "complementarity"):
        counts = report["by_kind"][kind]
        lines.append(f"- {kind}: {counts['passed']} passing, {counts['failed']} failing")
    lines += ["", "By pairwise scope:", ""]
    for pair in report["pairs"]:
        counts = report["by_pair"].get(pair, {"passed": 0, "failed": 0})
        lines.append(f"- {pair}: {counts['passed']} passing, {counts['failed']} failing")
    lines.append("")

    for entry in CORRESPONDENCES:
        result = results[entry.key]
        mark = "PASS" if result.passed else "FAIL"
        lines += [
            f"## `{entry.key}`",
            "",
            f"**{entry.kind}** / **{entry.status}** / **{entry.pair}** / probe {mark}",
            "",
            entry.claim,
            "",
            f"- OPH: {entry.oph}",
            f"- FEP: {entry.fep}",
            f"- Synergetics: {entry.synergetics}",
            f"- Source: {entry.source}",
            "",
            "Probe values:",
            "",
        ]
        for name, value in result.values.items():
            lines.append(f"- `{name}` = {format_registry_measurement(name, value)}")
        lines.append("")
    return "\n".join(lines) + "\n"


def render_values() -> str:
    lines = [
        "# Manuscript values",
        "",
        "<!-- generated by scripts/render_docs.py; edit the values, then re-render -->",
        "",
        "Every number the manuscript may quote, with the source that establishes it.",
        "`Value` is what the prose says; `Exact` is the form the source gives where it",
        "gives one; `Note` records what is measured rather than quoted.",
        "",
        "| key | value | exact | source | note |",
        "| --- | --- | --- | --- | --- |",
    ]
    for entry in MANUSCRIPT_VALUES:
        exact = f"`{entry.exact}`" if entry.exact else ""
        note = entry.note or ""
        value = format_registry_measurement(entry.key, entry.value)
        lines.append(
            f"| `{entry.key}` | {value} | {exact} | {entry.source} | {note} |",
        )
    lines.append("")
    return "\n".join(lines)


def render_concordance() -> str:
    """Render where each claim is stated and where each figure appears.

    Derived only from the registry and the manuscript text, never from
    ``output/``: a fresh clone with no rendered artefacts must render the same
    document byte for byte. The registry table in ``03_method.md`` names every
    key by construction, so its table rows are stripped before scanning that
    section; what survives is where a claim is argued in prose.
    """
    manuscript = ROOT / "manuscript"
    # Only main prose can supply the primary location of a registry claim.
    sections = read_sections(manuscript)
    sections[ONTOLOGY_FILENAME] = render_ontology()
    references = index_references(sections)
    authored = {name: text for name, text in sections.items() if name != ONTOLOGY_FILENAME}
    table_row = re.compile(r"^\| `[a-z0-9-]+` \|")
    authored_prose = dict(authored)
    authored_prose["03_method.md"] = "\n".join(
        line for line in authored["03_method.md"].splitlines() if not table_row.match(line)
    )
    claim_mentions = {
        name: set(re.findall(r"`([a-z0-9-]+)`", text)) for name, text in authored_prose.items()
    }
    named_by = {entry.key: [name for name, keys in claim_mentions.items() if entry.key in keys]
                for entry in CORRESPONDENCES}
    outline = manuscript / "MANUSCRIPT_STATUS.md"
    outline_text = outline.read_text(encoding="utf-8")

    lines = [
        "# Concordance",
        "",
        "<!-- generated by scripts/render_docs.py; edit the registry, the sections or the outline, then re-render -->",
        "",
        "Where each claim is stated and where each figure appears, read from the",
        "registry and the manuscript itself. The registry table in `03_method.md`",
        "names every key, so its table rows do not count as a mention here; the",
        "outline in `MANUSCRIPT_STATUS.md` plans each section's entries. A claim",
        "carried only by the table and the outline is a claim the prose does not yet",
        "argue by key.",
        "",
        "| key | kind | status | pair | named in prose (outside the registry table) | outlined in |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for entry in CORRESPONDENCES:
        named = named_by[entry.key]
        prose = ", ".join(f"`{name}`" for name in named) if named else "*no section names it*"
        outlined = "yes" if f"`{entry.key}`" in outline_text else "**no**"
        lines.append(
            f"| `{entry.key}` | {entry.kind} | {entry.status} | {entry.pair} | {prose} | {outlined} |"
        )
    argued = sum(1 for named in named_by.values() if named)
    lines += [
        "",
        f"{argued} of {len(CORRESPONDENCES)} claims are named by at least one section's prose.",
        "",
        "## Sections",
        "",
        "| section | claims its prose names |",
        "| --- | --- |",
    ]
    for name in authored:
        keys_here = [entry.key for entry in CORRESPONDENCES if name in named_by[entry.key]]
        cell = ", ".join(f"`{key}`" for key in keys_here) if keys_here else "*none*"
        lines.append(f"| `{name}` | {cell} |")
    lines += [
        "",
        "## Figures",
        "",
        "| figure | declared in | cited by | probe sources of values quoted in the caption |",
        "| --- | --- | --- | --- |",
    ]

    def chapters(names: Sequence[str]) -> str:
        return ", ".join(f"[`{name}`](../manuscript/{name})" for name in names) if names else "*never cited*"

    probe_of_token = {
        token_for(entry.key): entry.source.split(":")[1]
        for entry in MANUSCRIPT_VALUES
        if entry.source.startswith("probe:")
    }
    for figure in sorted(references.figures, key=lambda row: row.label):
        tokens = TOKEN_CAPTION.findall(figure.caption)
        sources = [f"`{key}`" for key in sorted({probe_of_token[token] for token in tokens if token in probe_of_token})]
        if any(token.startswith("REGISTRY_") for token in tokens):
            sources.append("*registry totals*")
        label = figure.label
        lines.append(f"| `{label}` | {chapters(references.declared[label])} | "
                     f"{chapters(references.cited_by.get(label, ()))} | {', '.join(sources) or '*none*'} |")
    lines += [
        "",
        "## Tables",
        "",
        "| table | declared in | cited by |",
        "| --- | --- | --- |",
    ]
    for label in references.labels("tbl"):
        lines.append(f"| `{label}` | {chapters(references.declared[label])} | "
                     f"{chapters(references.cited_by.get(label, ()))} |")
    lines += [
        "",
        "## Formal statements and equations",
        "",
        "| label | kind | stated in | cited by |",
        "| --- | --- | --- | --- |",
    ]
    for kind in ("def", "prop", "eq", "thm", "lem", "cor", "rmk", "exa"):
        for label in references.labels(kind):
            lines.append(f"| `{label}` | {kind} | {chapters(references.declared[label])} | "
                         f"{chapters(references.cited_by.get(label, ()))} |")
    lines += [
        "",
        "## Values",
        "",
        "| token | quoted in |",
        "| --- | --- |",
    ]
    quoted: dict[str, list[str]] = {}
    for name, text in sections.items():
        for token in dict.fromkeys(TOKEN_CAPTION.findall(text)):
            quoted.setdefault(token, []).append(name)
    for token in sorted(quoted):
        lines.append(f"| `{{{{{token}}}}}` | " + ", ".join(f"`{name}`" for name in quoted[token]) + " |")
    lines += [
        "",
        f"{len(quoted)} of the bound values are quoted by the prose. The cover is",
        "placed by `manuscript/config.yaml`; the accessibility registry that gives",
        "each figure its alternative text is `output/figures/figure_registry.json`,",
        "written by `scripts/make_figures.py`.",
        "",
    ]
    return "\n".join(lines)


def render_ontology() -> str:
    """Render the structured terminology supplement and resolve its evidence links."""
    document = json.loads(ONTOLOGY_SOURCE.read_text(encoding="utf-8"))
    if document.get("schema") != 1:
        raise ValueError("unsupported ontology concordance schema")
    programmes = {"oph": "OPH", "fep": "FEP", "synergetics": "Synergetics"}
    relations = {
        "source-usage": "Source usage",
        "distinction": "Distinction",
        "model-correspondence": "Model correspondence",
        "conditional-identity": "Conditional identity",
        "counterexample": "Counterexample",
        "geometric-comparison": "Geometric comparison",
    }
    registry_keys = {entry.key for entry in CORRESPONDENCES}
    references = (ROOT / "manuscript" / "references.bib").read_text(encoding="utf-8")
    bibliography_keys = set(re.findall(r"(?m)^\s*@\w+\{\s*([^,\s]+)\s*,", references))
    sources = {pin.id: pin for pin in load_sources(ROOT / "data" / "sources.json")}
    group_ids: set[str] = set()
    term_ids: set[str] = set()
    lines = [
        "# Ontology concordance {#sec:ontology-concordance}",
        "",
        "<!-- generated by scripts/render_docs.py from data/ontology_concordance.json -->",
        "",
        "The supplement compares what shared terms name in the finite models.",
        "Source usage and distinctions describe terminology. Model correspondences,",
        "conditional identities, counterexamples and geometric comparisons point to",
        "the registry for their executable evidence. The scope column identifies",
        "assumptions and the limits of the comparison.",
        "",
        "The structured records in `data/ontology_concordance.json` give stable",
        "term identifiers, meanings by programme and pointers to cited identifiers",
        "in the pinned source register. Run `oph-fep-synergetics verify --key KEY`",
        "to inspect the values for a listed probe.",
    ]
    for group in document["groups"]:
        group_id = group["id"]
        if group_id in group_ids or not re.fullmatch(r"[a-z][a-z0-9-]*", group_id):
            raise ValueError(f"invalid or duplicate ontology group {group_id!r}")
        if group_ids:
            lines += ["", r"\clearpage"]
        group_ids.add(group_id)
        lines += [
            "",
            f"## {group['title']}",
            "",
            "| Term | Meaning by programme | Relationship and scope | Evidence |",
            "|:-------------|:------------------------------|:------------------------------|:------------------------|",
        ]
        for entry in group["entries"]:
            term_id = entry["id"]
            if term_id in term_ids or not re.fullmatch(r"[a-z][a-z0-9-]*", term_id):
                raise ValueError(f"invalid or duplicate ontology term {term_id!r}")
            term_ids.add(term_id)
            meanings = entry["meanings"]
            if not meanings or meanings.keys() - programmes.keys():
                raise ValueError(f"{term_id}: expected meanings from the declared programmes")
            relation = entry["relation"]
            if relation not in relations:
                raise ValueError(f"{term_id}: unknown ontology relation {relation!r}")
            probes, citations = entry["probes"], entry["citations"]
            if relation not in {"source-usage", "distinction"} and not probes:
                raise ValueError(f"{term_id}: {relation} requires an executable probe")
            unknown = (set(probes) - registry_keys) | (set(citations) - bibliography_keys)
            if unknown or not citations:
                raise ValueError(f"{term_id}: expected cited evidence, unknown keys {sorted(unknown)}")
            for pointer in entry.get("pinned_sources", []):
                source_id, symbol = pointer["id"], pointer.get("symbol")
                if source_id not in sources:
                    raise ValueError(f"{term_id}: unknown source pin {source_id!r}")
                if symbol is not None:
                    try:
                        sources[source_id].identifier(symbol)
                    except KeyError as exc:
                        raise ValueError(f"{term_id}: unknown {source_id} identifier {symbol!r}") from exc
            meaning_text = " ".join(
                f"**{name}.** {meanings[key]}" for key, name in programmes.items() if key in meanings
            )
            relation_text = f"**{relations[relation]}.** {entry['limit']}"
            probe_text = ", ".join(f"`{key}`" for key in probes)
            citation_text = "[" + "; ".join(f"@{key}" for key in citations) + "]"
            evidence = f"{probe_text}. {citation_text}" if probes else citation_text
            cells = (entry["term"], meaning_text, relation_text, evidence)
            lines.append("| " + " | ".join(cell.replace("|", "\\|") for cell in cells) + " |")
        lines += ["", f": {group['title']} in the compared models. {{#tbl:ontology-{group_id}}}"]
    return "\n".join(lines) + "\n"


def display_path(path: Path) -> Path:
    """Render a path relative to the project root when it is inside it."""
    try:
        return path.relative_to(ROOT)
    except ValueError:
        return path


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write; exit non-zero when a document is out of date",
    )
    args = parser.parse_args(argv)
    rendered = {
        REGISTRY_DOC: render_registry(),
        VALUES_DOC: render_values(),
        CONCORDANCE_DOC: render_concordance(),
        ONTOLOGY_DOC: render_ontology(),
    }
    stale = []
    for path, text in rendered.items():
        if args.check:
            current = path.read_text(encoding="utf-8") if path.is_file() else ""
            if current != text:
                stale.append(path)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"wrote {display_path(path)}")
    if stale:
        for path in stale:
            print(f"out of date: {display_path(path)}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
