"""Render the correspondence registry, the bound values and the concordance.

The registry and ``MANUSCRIPT_VALUES`` are the sources of truth, so the
reference documents are generated rather than hand-copied: a change to a claim,
a status or a probe value shows up in the next render and can be reviewed as an
ordinary diff.

Usage::

    python scripts/render_docs.py            # write the documents
    python scripts/render_docs.py --check    # fail if they are out of date
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import Sequence

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from oph_fep_synergetics.analysis import CORRESPONDENCES, summary, verify  # noqa: E402
from oph_fep_synergetics.manuscript_variables import MANUSCRIPT_VALUES  # noqa: E402

DOCS = ROOT / "docs"

REGISTRY_DOC = DOCS / "CORRESPONDENCES.md"
VALUES_DOC = DOCS / "MANUSCRIPT_VALUES.md"
CONCORDANCE_DOC = DOCS / "CONCORDANCE.md"


def format_value(value: object) -> str:
    """Render a probe value or bound value compactly and unambiguously."""
    if isinstance(value, dict):
        return ", ".join(f"{key}={format_value(item)}" for key, item in value.items())
    if isinstance(value, (tuple, list)):
        return "(" + ", ".join(format_value(item) for item in value) + ")"
    if isinstance(value, float):
        return f"{value!r}"
    return str(value)


def render_registry() -> str:
    results = {result.key: result for result in verify()}
    report = summary(tuple(results.values()))
    lines = [
        "# Correspondence registry",
        "",
        "<!-- generated by scripts/render_docs.py; edit the registry, then re-render -->",
        "",
        "One executable probe per entry. Each entry carries the operator-algebraic",
        "reading from Observer Patch Holography, the variational reading from the",
        "Free Energy Principle, and the geometric reading from Fuller's Synergetics,",
        "together with the status the probe establishes and the pair of programmes the",
        "claim is made across. Most claims are pairwise; `three-way` marks the few that",
        "no pair of readings captures.",
        "",
        "| pair | kind | status | entry | claim |",
        "| --- | --- | --- | --- | --- |",
    ]
    for entry in CORRESPONDENCES:
        lines.append(
            f"| {entry.pair} | {entry.kind} | {entry.status} | `{entry.key}` | {entry.claim} |"
        )
    lines += [
        "",
        f"Totals: {report['passed']}/{report['total']} probes pass, "
        f"{report['failed']} fail.",
        "",
        "By kind:",
        "",
    ]
    for kind in ("isomorphism", "disagreement", "complementarity"):
        counts = report["by_kind"][kind]
        lines.append(f"- {kind}: {counts['passed']} passing, {counts['failed']} failing")
    lines += ["", "By pairwise scope:", ""]
    for pair in report["pairs"]:
        counts = report["by_pair"].get(pair, {"passed": 0, "failed": 0})
        lines.append(f"- {pair}: {counts['passed']} passing, {counts['failed']} failing")
    lines.append("")

    for entry in CORRESPONDENCES:
        result = results[entry.key]
        mark = "PASS" if result.passed else "FAIL"
        lines += [
            f"## `{entry.key}`",
            "",
            f"**{entry.kind}** / **{entry.status}** / **{entry.pair}** / probe {mark}",
            "",
            entry.claim,
            "",
            f"- OPH: {entry.oph}",
            f"- FEP: {entry.fep}",
            f"- Synergetics: {entry.synergetics}",
            f"- Source: {entry.source}",
            "",
            "Probe values:",
            "",
        ]
        for name, value in result.values.items():
            lines.append(f"- `{name}` = {format_value(value)}")
        lines.append("")
    return "\n".join(lines) + "\n"


def render_values() -> str:
    lines = [
        "# Manuscript values",
        "",
        "<!-- generated by scripts/render_docs.py; edit the values, then re-render -->",
        "",
        "Every number the manuscript may quote, with the source that establishes it.",
        "`Value` is what the prose says; `Exact` is the form the source gives where it",
        "gives one; `Note` records what is measured rather than quoted.",
        "",
        "| key | value | exact | source | note |",
        "| --- | --- | --- | --- | --- |",
    ]
    for entry in MANUSCRIPT_VALUES:
        exact = f"`{entry.exact}`" if entry.exact else ""
        note = entry.note or ""
        lines.append(
            f"| `{entry.key}` | {format_value(entry.value)} | {exact} | {entry.source} | {note} |"
        )
    lines.append("")
    return "\n".join(lines)


def render_concordance() -> str:
    """Render where each claim is stated and where each figure appears.

    Derived only from the registry and the manuscript text, never from
    ``output/``: a fresh clone with no rendered artefacts must render the same
    document byte for byte. The registry table in ``03_method.md`` names every
    key by construction, so its table rows are stripped before scanning that
    section; what survives is where a claim is argued in prose.
    """
    manuscript = ROOT / "manuscript"
    section_paths = sorted(manuscript.glob("[0-9]*.md"))
    table_row = re.compile(r"^\| `[a-z0-9-]+` \|")
    figure_link = re.compile(
        r"\]\(\.\./output/figures/(fig_[a-z0-9_]+\.png)\)\{#fig:([a-z0-9_-]+)"
    )

    def naming(key: str) -> list[str]:
        named: list[str] = []
        for path in section_paths:
            text = path.read_text(encoding="utf-8")
            if path.name == "03_method.md":
                text = "\n".join(
                    line for line in text.splitlines() if not table_row.match(line)
                )
            if key in text:
                named.append(path.name)
        return named

    named_by = {entry.key: naming(entry.key) for entry in CORRESPONDENCES}
    outline = manuscript / "MANUSCRIPT_STATUS.md"
    outline_text = outline.read_text(encoding="utf-8")

    lines = [
        "# Concordance",
        "",
        "<!-- generated by scripts/render_docs.py; edit the registry, the sections or the outline, then re-render -->",
        "",
        "Where each claim is stated and where each figure appears, read from the",
        "registry and the manuscript itself. The registry table in `03_method.md`",
        "names every key, so its table rows do not count as a mention here; the",
        "outline in `MANUSCRIPT_STATUS.md` plans each section's entries. A claim",
        "carried only by the table and the outline is a claim the prose does not yet",
        "argue by key.",
        "",
        "| key | kind | status | pair | named in prose (outside the registry table) | outlined in |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for entry in CORRESPONDENCES:
        named = named_by[entry.key]
        prose = ", ".join(f"`{name}`" for name in named) if named else "*no section names it*"
        outlined = "yes" if f"`{entry.key}`" in outline_text else "**no**"
        lines.append(
            f"| `{entry.key}` | {entry.kind} | {entry.status} | {entry.pair} | {prose} | {outlined} |"
        )
    argued = sum(1 for named in named_by.values() if named)
    lines += [
        "",
        f"{argued} of {len(CORRESPONDENCES)} claims are named by at least one section's prose.",
        "",
        "## Sections",
        "",
        "| section | claims its prose names |",
        "| --- | --- |",
    ]
    for path in section_paths:
        keys_here = [entry.key for entry in CORRESPONDENCES if path.name in named_by[entry.key]]
        cell = ", ".join(f"`{key}`" for key in keys_here) if keys_here else "*none*"
        lines.append(f"| `{path.name}` | {cell} |")
    lines += [
        "",
        "## Figures",
        "",
        "| figure | included by |",
        "| --- | --- |",
    ]
    included: dict[str, list[str]] = {}
    for path in section_paths:
        for _, label in figure_link.findall(path.read_text(encoding="utf-8")):
            included.setdefault(label, []).append(path.name)
    for label in sorted(included):
        lines.append(f"| `fig:{label[4:].replace('_', '-')}` | " + ", ".join(f"`{name}`" for name in included[label]) + " |")
    lines += [
        "",
        f"{len(included)} distinct figures are included by the sections; the cover is",
        "placed by `manuscript/config.yaml`. The accessibility registry that gives",
        "each figure its alternative text is `output/figures/figure_registry.json`,",
        "written by `scripts/make_figures.py`.",
        "",
    ]
    return "\n".join(lines)


def display_path(path: Path) -> Path:
    """Render a path relative to the project root when it is inside it."""
    try:
        return path.relative_to(ROOT)
    except ValueError:
        return path


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write; exit non-zero when a document is out of date",
    )
    args = parser.parse_args(argv)
    rendered = {REGISTRY_DOC: render_registry(), VALUES_DOC: render_values(), CONCORDANCE_DOC: render_concordance()}
    stale = []
    for path, text in rendered.items():
        if args.check:
            current = path.read_text(encoding="utf-8") if path.is_file() else ""
            if current != text:
                stale.append(path)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"wrote {display_path(path)}")
    if stale:
        for path in stale:
            print(f"out of date: {display_path(path)}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
